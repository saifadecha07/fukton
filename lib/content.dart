String greeting(DateTime t) {
  final h = t.hour;
  if (h >= 4 && h < 11) return 'อรุณสวัสดิ์';
  if (h >= 11 && h < 16) return 'สวัสดียามบ่าย';
  if (h >= 16 && h < 19) return 'สายัณห์สวัสดิ์';
  return 'ราตรีสวัสดิ์';
}

